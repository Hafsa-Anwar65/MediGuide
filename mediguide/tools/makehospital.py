#!/usr/bin/env python3
"""
Generates the Gazebo hospital world and the matching 2D map from ONE list of
walls, so the map always matches the world.

    python3 tools/makehospital.py

Writes:
    worlds/hospital.world
    maps/hospital.pgm
    maps/hospital.yaml

Layout (metres):

  y=4  +-----------+
       |   Ward    |
       |           |
  y=1  +---  ------+--------------------------+-----------+
       |              Corridor           door   Pharmacy  |
  y=-1 +--------------------------------------------------+
      x=0                                    x=12       x=15
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)

T = 0.15      # wall thickness
H = 1.0       # wall height

# Each wall: (x1, y1, x2, y2) - horizontal or vertical line
WALLS = [
    # outer south wall
    (0.0, -1.0, 15.0, -1.0),
    # west wall
    (0.0, -1.0, 0.0, 4.0),
    # ward back wall and east wall
    (0.0, 4.0, 4.5, 4.0),
    (4.5, 1.0, 4.5, 4.0),
    # corridor north wall with the ward door (1 m wide at x = 2.5)
    (0.0, 1.0, 2.0, 1.0),
    (3.0, 1.0, 12.0, 1.0),
    # pharmacy: door at x = 12, y = -0.5 .. 0.5
    (12.0, -1.0, 12.0, -0.5),
    (12.0, 0.5, 12.0, 1.0),
    (12.0, 1.0, 15.0, 1.0),
    (15.0, -1.0, 15.0, 1.0),
]

# Furniture (x, y, size_x, size_y, height) - pharmacy counter and ward beds
BOXES = [
    (14.6, 0.0, 0.5, 1.4, 0.9),     # pharmacy counter
    (1.2, 3.4, 1.0, 0.6, 0.5),      # bed in the ward
]

# Map settings
RES = 0.05
X_MIN, Y_MIN, X_MAX, Y_MAX = -1.0, -2.0, 16.0, 5.0


def wall_box(w):
    x1, y1, x2, y2 = w
    cx, cy = (x1 + x2) / 2.0, (y1 + y2) / 2.0
    if abs(y1 - y2) < 1e-6:          # horizontal
        sx, sy = abs(x2 - x1) + T, T
    else:                            # vertical
        sx, sy = T, abs(y2 - y1) + T
    return cx, cy, sx, sy


def all_boxes():
    out = []
    for w in WALLS:
        cx, cy, sx, sy = wall_box(w)
        out.append(("wall", cx, cy, sx, sy, H))
    for b in BOXES:
        out.append(("furniture",) + b)
    return out


def write_world(path):
    models = []
    for i, (kind, cx, cy, sx, sy, h) in enumerate(all_boxes()):
        if kind == "wall":
            color = "0.85 0.85 0.85 1"
        else:
            color = "0.35 0.55 0.8 1"
        models.append("""
    <model name="{kind}_{i}">
      <static>true</static>
      <pose>{cx:.3f} {cy:.3f} {hz:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry>
          <material>
            <ambient>{color}</ambient>
            <diffuse>{color}</diffuse>
          </material>
        </visual>
      </link>
    </model>""".format(kind=kind, i=i, cx=cx, cy=cy, hz=h / 2.0, sx=sx, sy=sy, h=h, color=color))

    world = """<?xml version="1.0"?>
<!-- Generated by tools/makehospital.py - edit that file, not this one -->
<sdf version="1.6">
  <world name="hospital">
    <include><uri>model://ground_plane</uri></include>
    <include><uri>model://sun</uri></include>
    <physics type="ode">
      <real_time_update_rate>1000.0</real_time_update_rate>
      <max_step_size>0.001</max_step_size>
    </physics>
    <gui fullscreen="0">
      <camera name="user_camera">
        <pose>7.5 -9 14 0 0.95 1.5708</pose>
      </camera>
    </gui>{models}
  </world>
</sdf>
""".format(models="".join(models))
    with open(path, "w") as f:
        f.write(world)


def write_map(pgm_path, yaml_path):
    w = int(round((X_MAX - X_MIN) / RES))
    h = int(round((Y_MAX - Y_MIN) / RES))
    FREE, OCC = 254, 0
    grid = [[FREE] * w for _ in range(h)]

    for kind, cx, cy, sx, sy, _ in all_boxes():
        x0, x1 = cx - sx / 2.0, cx + sx / 2.0
        y0, y1 = cy - sy / 2.0, cy + sy / 2.0
        c0 = int((x0 - X_MIN) / RES)
        c1 = int((x1 - X_MIN) / RES)
        r0 = int((y0 - Y_MIN) / RES)
        r1 = int((y1 - Y_MIN) / RES)
        for r in range(max(r0, 0), min(r1 + 1, h)):
            for c in range(max(c0, 0), min(c1 + 1, w)):
                grid[h - 1 - r][c] = OCC      # image row 0 is the top (max y)

    with open(pgm_path, "wb") as f:
        f.write(("P5\n# MediGuide hospital map\n%d %d\n255\n" % (w, h)).encode())
        for row in grid:
            f.write(bytes(row))

    with open(yaml_path, "w") as f:
        f.write("image: hospital.pgm\n")
        f.write("resolution: %.3f\n" % RES)
        f.write("origin: [%.1f, %.1f, 0.0]\n" % (X_MIN, Y_MIN))
        f.write("negate: 0\n")
        f.write("occupied_thresh: 0.65\n")
        f.write("free_thresh: 0.196\n")


if __name__ == "__main__":
    write_world(os.path.join(PKG, "worlds", "hospital.world"))
    write_map(os.path.join(PKG, "maps", "hospital.pgm"), os.path.join(PKG, "maps", "hospital.yaml"))
    print("World and map written.")
